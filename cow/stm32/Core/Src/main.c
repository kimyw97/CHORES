	HAL_Delay(3000);
	startEncoder(&htim3);
	startEncoder(&htim2);
	__HAL_TIM_SET_COUNTER(&htim3, 0);
	__HAL_TIM_SET_COUNTER(&htim2, 0);
	int8_t target_distance_cm = 100;
	int8_t PPR = 11;
	int8_t GEAR_RATIO = 30;
	float WHEEL_CIRCUMFERENCE_CM = 2 * 3.1415 * 3.5;
